public class IntegerTypes {

    public static void main(String[] args) {

        byte b = 100;

        short s = 25000;

        int i = 1000000;

        long l = 9876543210L;

        System.out.println(b);

        System.out.println(s);

        System.out.println(i);

        System.out.println(l);

    }

}